#!/usr/bin/env python3
"""Move ASR word timings onto the film clock and emit js/words.js.

    python align_words.py --words narr/words.json --lead 0.10

The narration file is placed LEAD seconds into the film by mix.py. Words must be
recognised on the already-tightened voice file, so their times are final; this
script only offsets them, repairs overlaps and enforces a minimum word length.
"""
import argparse
import json
import os
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass


def load_words(path):
    data = json.load(open(path, encoding="utf-8"))
    out = []
    for w in data:
        if isinstance(w, (list, tuple)):
            out.append((str(w[0]), float(w[1]), float(w[2])))
        else:
            out.append((str(w["word"]), float(w["start"]), float(w["end"])))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--words", required=True, help="ASR JSON: [{word,start,end}, ...]")
    ap.add_argument("--lead", type=float, default=0.10, help="film time of the first voice sample")
    ap.add_argument("--min-dur", type=float, default=0.05)
    ap.add_argument("--out", default="js/words.js")
    ap.add_argument("--json-out", default="build/film_words.json")
    args = ap.parse_args()

    raw = sorted(load_words(args.words), key=lambda w: w[1])
    if not raw:
        sys.exit("no words")
    fixed = []
    prev_end = -1.0
    for word, s, e in raw:
        s = max(0.0, s + args.lead, prev_end)
        e = max(e + args.lead, s + args.min_dur)
        if fixed and s < fixed[-1][2] - 1e-6:
            s = fixed[-1][2]
            e = max(e, s + args.min_dur)
        fixed.append([word, round(s, 3), round(e, 3)])
        prev_end = e

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    os.makedirs(os.path.dirname(args.json_out) or ".", exist_ok=True)
    json.dump(fixed, open(args.json_out, "w", encoding="utf-8"), ensure_ascii=False)
    body = ",\n  ".join(json.dumps(w, ensure_ascii=False) for w in fixed)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("// generated by build/align_words.py: [word, start, end] in film seconds\n")
        f.write("window.WORDS = [\n  " + body + "\n];\n")

    print(f"{len(fixed)} words, {fixed[0][1]:.2f}s -> {fixed[-1][2]:.2f}s")
    print(f"wrote {args.out} and {args.json_out}")
    print("first:", fixed[:3])
    print("last:", fixed[-3:])


if __name__ == "__main__":
    main()
